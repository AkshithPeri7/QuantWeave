def seed_demo_financial_statements(db: Session) -> int:
    """
    Seeds synthetic financial statements for all available demo equity instruments.
    Returns the total number of financial statements inserted/updated.
    """
    # Ensure DataSource exists
    ds = (
        db.query(DataSource)
        .filter(DataSource.provider_name == "demo_financials", DataSource.dataset == "synthetic_statements_v1")
        .first()
    )
    if not ds:
        ds = DataSource(
            provider_name="demo_financials",
            dataset="synthetic_statements_v1",
            terms_url="https://quantweave.local/terms/demo-financials",
        )
        db.add(ds)
        db.commit()
        db.refresh(ds)

    total_statements = 0

    for symbol, statements in DEMO_FINANCIAL_DATA.items():
        instrument = db.query(Instrument).filter(Instrument.symbol == symbol).first()
        if not instrument:
            continue

        for stmt_data in statements:
            q = stmt_data.get("fiscal_quarter") or 0
            existing = (
                db.query(FinancialStatement)
                .filter(
                    FinancialStatement.instrument_id == instrument.id,
                    FinancialStatement.period_type == stmt_data["period_type"],
                    FinancialStatement.fiscal_year == stmt_data["fiscal_year"],
                    FinancialStatement.fiscal_quarter == q,
                )
                .first()
            )

            if existing:
                for k, v in stmt_data.items():
                    if k == "fiscal_quarter":
                        setattr(existing, k, q)
                    else:
                        setattr(existing, k, v)
                existing.provider_id = ds.id
                existing.is_synthetic = True
            else:
                new_stmt = FinancialStatement(
                    instrument_id=instrument.id,
                    provider_id=ds.id,
                    statement_type=stmt_data["period_type"],
                    period_type=stmt_data["period_type"],
                    fiscal_year=stmt_data["fiscal_year"],
                    fiscal_quarter=q,
                    period_start_date=stmt_data.get("period_start_date"),
                    period_end_date=stmt_data["period_end_date"],
                    filing_date=stmt_data.get("period_end_date"),
                    currency="INR",
                    is_synthetic=True,
                    revenue=stmt_data.get("revenue"),
                    cost_of_goods_sold=stmt_data.get("cost_of_goods_sold"),
                    gross_profit=stmt_data.get("gross_profit"),
                    operating_expenses=stmt_data.get("operating_expenses"),
                    operating_income=stmt_data.get("operating_income"),
                    interest_expense=stmt_data.get("interest_expense"),
                    tax_expense=stmt_data.get("tax_expense"),
                    net_income=stmt_data.get("net_income"),
                    diluted_shares=stmt_data.get("diluted_shares"),
                    eps=stmt_data.get("eps"),
                    cash_and_equivalents=stmt_data.get("cash_and_equivalents"),
                    total_current_assets=stmt_data.get("total_current_assets"),
                    total_non_current_assets=stmt_data.get("total_non_current_assets"),
                    total_assets=stmt_data.get("total_assets"),
                    total_current_liabilities=stmt_data.get("total_current_liabilities"),
                    total_long_term_debt=stmt_data.get("total_long_term_debt"),
                    total_debt=stmt_data.get("total_debt"),
                    total_liabilities=stmt_data.get("total_liabilities"),
                    shareholder_equity=stmt_data.get("shareholder_equity"),
                    book_value_per_share=stmt_data.get("book_value_per_share"),
                    operating_cash_flow=stmt_data.get("operating_cash_flow"),
                    capital_expenditures=stmt_data.get("capital_expenditures"),
                    free_cash_flow=stmt_data.get("free_cash_flow"),
                )
                db.add(new_stmt)
            total_statements += 1

    db.commit()
    return total_statements
